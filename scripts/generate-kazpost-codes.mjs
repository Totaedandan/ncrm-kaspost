// Regenerates src/infrastructure/tracking/kazpost-status-codes.ts from Kazpost's official status
// dictionary (https://post.kz/static/new_mappings.json, referenced by the Open API docs:
// https://open.post.kz, method "Сервис трекинга по трек-номеру").
//
// Usage: node scripts/generate-kazpost-codes.mjs [path/to/new_mappings.json]
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';

const source = process.argv[2] ?? 'tests/fixtures/kazpost/new_mappings.json';
const target = 'src/infrastructure/tracking/kazpost-status-codes.ts';
const dictionary = JSON.parse(readFileSync(source, 'utf8'));

// Codes whose meaning the dictionary's coarse "type" column does not capture.
const RETURNED = new Set(['ReturnedCompany', 'RETCC']);
const RETURNING = new Set(['ReturnedToCompany', 'RET', 'RETSTR', 'RETSC', 'RETSCSTR', 'CUSTOM_RET', 'ReturnedPVZ']);
const REGISTERED = new Set(['Registered', 'BAT', 'RCPOPS', 'RCP', 'EMA']);
const DELIVERED = new Set(['HandedPVZ']);
const OUT_FOR_DELIVERY = new Set(['EDG', 'DLV', 'DLV_HAND']);
const WAITING_AT_OFFICE = new Set(['DeliveredPVZ']);

function classify(code, entry) {
  if (!entry.show) return null; // "Не транслировать в клиентский сервис"
  const base = code.replace(/_[IO]$/, '');
  if (RETURNED.has(base)) return 'RETURNED';
  if (RETURNING.has(base)) return 'RETURNING';
  if (REGISTERED.has(base)) return 'REGISTERED';
  if (DELIVERED.has(base)) return 'DELIVERED';
  if (OUT_FOR_DELIVERY.has(base)) return 'IN_TRANSIT';
  if (WAITING_AT_OFFICE.has(base)) return 'ARRIVED_AT_OFFICE';

  const type = entry.type.trim().toLowerCase();
  if (type === 'вручено') return 'DELIVERED';
  if (type.startsWith('прибыло и ожидает') || type === 'в ожидании клиента' || type === 'прибыло') {
    return 'ARRIVED_AT_OFFICE';
  }
  return 'IN_TRANSIT';
}

// Internal codes seen in real responses (e.g. track AV005201643KZ) but absent from the official
// dictionary. They are siblings of the documented hidden Act_* codes. Add new finds here.
const OBSERVED_INTERNAL = ['New_act_B', 'New_act_G', 'New_act', 'Send_act', 'Delete_act'];
for (const code of OBSERVED_INTERNAL) {
  dictionary[code] ??= { show: 0, type: 'observed internal code', mapping: 'Внутренний код (нет в справочнике)' };
}

const rows = Object.entries(dictionary)
  .map(([code, entry]) => ({ code, status: classify(code, entry), text: entry.mapping.trim() }))
  .sort((a, b) => a.code.localeCompare(b.code));

const lines = rows.map(
  ({ code, status, text }) =>
    `  ${JSON.stringify(code)}: { status: ${status === null ? 'null' : `'${status}'`}, label: ${JSON.stringify(text)} },`,
);

const output = `// GENERATED by scripts/generate-kazpost-codes.mjs from Kazpost's official status dictionary.
// Do not edit by hand: change the classification rules in the script and regenerate.
import type { TrackingStatus } from '../../domain/tracking-status';

export interface KazpostCodeInfo {
  /** null = the code is internal ("do not show to customers") and must be ignored. */
  status: TrackingStatus | null;
  label: string;
}

export const KAZPOST_CODES: Readonly<Record<string, KazpostCodeInfo>> = {
${lines.join('\n')}
};
`;

writeFileSync(target, output, 'utf8');
process.stdout.write(`wrote ${rows.length} codes to ${target}\n`);
